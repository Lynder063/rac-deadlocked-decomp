#!/usr/bin/env python3
"""
Pair the functions of the libgcc objects (build/libgcc/*.o, tools/build_libgcc.sh)
with retail functions, and write config/libgcc.tsv: object, symbol, address.
A pair needs the same size and the same code with relocatable fields masked.
Only the libgcc range of core_text is searched.
"""
import glob
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import retail as mp  # noqa: E402
from elftools.elf.elffile import ELFFile  # noqa: E402

ROOT = mp.ROOT
LO, HI = 0x12EE30, 0x131A00


def main() -> int:
    funcs = []
    for l in (ROOT / "config" / "functions.tsv").read_text().splitlines():
        if l and not l.startswith("#"):
            n, a, s, _ = l.split("\t")
            a, s = int(a, 16), int(s, 16)
            if LO <= a < HI:
                funcs.append((a, s, n))
    with open(ROOT / "baserom" / "SCUS_974.65.elf", "rb") as f:
        secs = mp.sections(ELFFile(f))
    retail = {n: (a, s, mp.normalise(mp.read(secs, a, s))) for a, s, n in funcs}
    rows, taken = [], set()
    for path in sorted(glob.glob(str(ROOT / "build" / "libgcc" / "*.o"))):
        elf = ELFFile(open(path, "rb"))
        data = elf.get_section_by_name(".text").data()
        for s in elf.get_section_by_name(".symtab").iter_symbols():
            if s["st_info"]["type"] != "STT_FUNC" or not s["st_size"]:
                continue
            code = mp.normalise(data[s["st_value"]: s["st_value"] + s["st_size"]])
            hits = [n for n, (a, sz, c) in retail.items()
                    if sz == s["st_size"] and c == code and n not in taken]
            if len(hits) >= 1:
                n = hits[0]
                taken.add(n)
                rows.append((Path(path).stem, s.name, retail[n][0], retail[n][1]))
    rows.sort(key=lambda r: r[2])
    with open(ROOT / "config" / "libgcc.tsv", "w") as f:
        f.write("# object\tsymbol\taddress\tsize  (generated by tools/map_libgcc.py)\n")
        for o, sym, a, sz in rows:
            f.write("%s\t%s\t0x%08X\t0x%X\n" % (o, sym, a, sz))
    total = sum(r[3] for r in rows)
    print("%d libgcc functions match retail, %d bytes" % (len(rows), total))
    miss = [n for a, s, n in funcs if n not in taken]
    print("retail functions in range without a match: %d" % len(miss))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
