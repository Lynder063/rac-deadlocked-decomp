#!/usr/bin/env python3
"""
Split the level overlays into functions and group the identical ones.

Every level of the game carries its own overlay: a build of the level code
(`.text`, `.data`, `.bss`, `lvl.*vtbl`) loaded over the resident image when the
level starts. The 47 overlays share most of their code, at different
addresses, so functions are compared by their normalised code
(tools/retail.py), not by address.

Input: the overlay ELFs of an unpacked disc, `levels/**/overlay.elf`, as made by
the wrench build tool (`wrenchbuild unpack GAME.iso -o DIR -g dl -r us`).
Output (names, addresses and sizes only, no retail bytes):

  config/overlays.tsv           one row per overlay: id, directory, .text address, size
  config/overlay_functions.tsv  one row per distinct function:
                                name (func_<first level>_<address>), address, size, class, levels
    class   main     identical to a function of the resident level text
            common   in two or more overlays
            level    in exactly one overlay (its id is in `levels`)
    address is that of the first overlay in which the function occurs.

Function boundaries are found as in tools/find_functions.py: the section
start, every `jal` target inside it, and the instruction after a `jr $ra`
and its delay slot (skipping nops).

Usage: venv/bin/python tools/split_overlays.py UNPACKED_DIR
"""
import hashlib
import struct
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import retail as mp  # noqa: E402
from elftools.elf.elffile import ELFFile  # noqa: E402

ROOT = mp.ROOT
JR_RA = 0x03E00008


def functions(data: bytes, vram: int):
    """[(address, size, code)] of one .text section."""
    n = len(data) // 4
    w = struct.unpack("<%dI" % n, data[: n * 4])
    starts = {0}
    for i, x in enumerate(w):
        if x >> 26 == 3:  # jal
            tgt = ((x & 0x3FFFFFF) << 2) - vram
            if 0 <= tgt < n * 4:
                starts.add(tgt)
        if x == JR_RA and i + 2 < n:
            j = i + 2
            while j < n and w[j] == 0:
                j += 1
            if j < n:
                starts.add(j * 4)
    order = sorted(starts)
    out = []
    for k, s in enumerate(order):
        e = order[k + 1] if k + 1 < len(order) else n * 4
        out.append((vram + s, e - s, data[s:e]))
    return out


def digest(code: bytes) -> str:
    return hashlib.sha1(repr((len(code), mp.normalise(code))).encode()).hexdigest()


def main() -> int:
    src = Path(sys.argv[1])
    overlays = sorted(src.glob("levels/*/*/overlay.elf"),
                      key=lambda p: int(p.parent.name.split("_", 1)[0]))
    if not overlays:
        print("no levels/*/*/overlay.elf under", src)
        return 1
    # the resident level text, for the `main` class
    with open(ROOT / "baserom" / "SCUS_974.65.elf", "rb") as f:
        main_text = ELFFile(f).get_section_by_name(".text")
        main_funcs = functions(main_text.data(), main_text["sh_addr"])
    main_hashes = {digest(c) for _, _, c in main_funcs}

    seen = {}                      # digest -> [address, size, set(levels), first level]
    rows = []
    for idx, path in enumerate(overlays):
        d = path.parent
        lvl = "L%02d" % int(d.name.split("_", 1)[0])
        e = ELFFile(open(path, "rb"))
        t = e.get_section_by_name(".text")
        rows.append((lvl, "%s/%s" % (d.parent.name, d.name), t["sh_addr"], t["sh_size"]))
        for addr, size, code in functions(t.data(), t["sh_addr"]):
            h = digest(code)
            if h in seen:
                seen[h][2].add(lvl)
            else:
                seen[h] = [addr, size, {lvl}, lvl]
    with open(ROOT / "config" / "overlays.tsv", "w") as f:
        f.write("# id\tdirectory\ttext_address\ttext_size  (generated by tools/split_overlays.py)\n")
        for r in rows:
            f.write("%s\t%s\t0x%08X\t0x%X\n" % r)
    counts = defaultdict(lambda: [0, 0])
    with open(ROOT / "config" / "overlay_functions.tsv", "w") as f:
        f.write("# name\taddress\tsize\tclass\tlevels  (generated by tools/split_overlays.py)\n")
        for h, (addr, size, lv, first) in sorted(seen.items(), key=lambda kv: (kv[1][3], kv[1][0])):
            cls = "main" if h in main_hashes else "common" if len(lv) > 1 else "level"
            counts[cls][0] += 1
            counts[cls][1] += size
            f.write("func_%s_%08X\t0x%08X\t0x%X\t%s\t%s\n" % (first, addr, addr, size, cls, ",".join(sorted(lv))))
    print("%d overlays, %d distinct functions" % (len(rows), len(seen)))
    for c in ("main", "common", "level"):
        print("  %-7s %6d functions %9d bytes" % (c, counts[c][0], counts[c][1]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
