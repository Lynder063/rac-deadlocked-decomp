#!/usr/bin/env python3
"""
Write config/functions.tsv: every function splat found (name, address, size,
segment). Names, addresses and sizes only, no retail bytes, so it is
committed; the progress report reads it, and CI needs it without asm/.

Usage: python tools/gen_function_list.py        (needs asm/, tools/setup_asm.sh)
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def segment(dirname: str) -> str:
    return "text" if dirname.startswith("text") else dirname


def main() -> int:
    rows = []
    for p in (ROOT / "asm" / "nonmatchings").glob("*/func_*.s"):
        m = re.search(r"nonmatching (func_([0-9A-F]+)), 0x([0-9A-F]+)", p.read_text(errors="ignore")[:400])
        if m:
            rows.append((int(m.group(2), 16), int(m.group(3), 16), m.group(1), segment(p.parent.name)))
    rows.sort()
    with open(ROOT / "config" / "functions.tsv", "w") as f:
        f.write("# name\taddress\tsize\tsegment  (generated by tools/gen_function_list.py)\n")
        for addr, size, name, seg in rows:
            f.write("%s\t0x%08X\t0x%X\t%s\n" % (name, addr, size, seg))
    print("%d functions" % len(rows))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
